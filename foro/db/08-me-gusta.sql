--  · la versión en inglés (/en/...) comparte la cuenta con su original
--  · cualquiera puede leer las cuentas; nadie escribe la tabla directo:
--    se suma o se resta de a uno con la función tema_like_sumar
--  · la función solo actualiza páginas que ya están en la tabla, así nadie
--    puede crear filas inventadas; las páginas nuevas se agregan corriendo
--    de nuevo este archivo (el insert no pisa las cuentas existentes)
--  · el «ya me gustó» de cada visitante se guarda en su navegador
--    (no hay cuentas): es un contador de aprecio, no una votación
