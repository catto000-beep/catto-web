create table if not exists public.tema_like (
  pagina text primary key check (pagina ~ '^/publicaciones/[a-z0-9/_.-]+$' and length(pagina) <= 200),
  cuenta integer not null default 0 check (cuenta >= 0)
);

alter table public.tema_like enable row level security;
drop policy if exists tema_like_leer on public.tema_like;
create policy tema_like_leer on public.tema_like for select to anon, authenticated using (true);
revoke all on public.tema_like from anon, authenticated;
grant select on public.tema_like to anon, authenticated;

create or replace function public.tema_like_sumar(p_pagina text, p_delta integer)
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare v integer;
begin
  if p_delta is null or p_delta not in (1, -1) then
    raise exception 'delta inválido';
  end if;
  update public.tema_like
     set cuenta = greatest(cuenta + p_delta, 0)
   where pagina = p_pagina
  returning cuenta into v;
  return v;   -- null si la página no existe
end;
$$;

